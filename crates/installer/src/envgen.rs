use std::fmt;
use std::fs;
use std::path::Path;

use sha2::{Digest, Sha256};
use uuid::Uuid;

use crate::config::{ClusterMode, TopologySpec};
use crate::error::InstallerError;

/// Cryptographically random cluster secrets with mandatory Debug redaction.
#[derive(Clone, PartialEq, Eq)]
pub struct GeneratedSecrets {
    pub jwt_secret: String,
    pub credential_master_key: String,
    pub postgres_password: String,
    pub valkey_password: String,
    pub nats_nkey_seed: String,
    pub nats_public_nkey: String,
}

impl fmt::Debug for GeneratedSecrets {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("GeneratedSecrets")
            .field("jwt_secret", &"[REDACTED]")
            .field("credential_master_key", &"[REDACTED]")
            .field("postgres_password", &"[REDACTED]")
            .field("valkey_password", &"[REDACTED]")
            .field("nats_nkey_seed", &"[REDACTED]")
            .field("nats_public_nkey", &self.nats_public_nkey)
            .finish()
    }
}

impl GeneratedSecrets {
    /// Generates fresh high-entropy secrets using the OS CSPRNG (`Uuid::new_v4` / `getrandom`).
    #[must_use]
    pub fn generate() -> Self {
        let jwt_secret = random_hex_256("jwt");
        let credential_master_key = random_hex_256("master");
        let postgres_password = random_hex_256("pg")[..36].to_owned();
        let valkey_password = random_hex_256("valkey")[..36].to_owned();
        let seed_hex = random_hex_256("nats-seed");
        let pub_hex = random_hex_256("nats-pub");
        Self {
            jwt_secret,
            credential_master_key,
            postgres_password,
            valkey_password,
            nats_nkey_seed: format!("SU{}", seed_hex[..54].to_ascii_uppercase()),
            nats_public_nkey: format!("UA{}", pub_hex[..54].to_ascii_uppercase()),
        }
    }
}

fn random_hex_256(domain_sep: &str) -> String {
    let mut hasher = Sha256::new();
    hasher.update(domain_sep.as_bytes());
    hasher.update(Uuid::new_v4().as_bytes());
    hasher.update(Uuid::new_v4().as_bytes());
    hasher.update(Uuid::new_v4().as_bytes());
    hex::encode(hasher.finalize())
}

/// Renders a complete `.env` configuration file ready for `0600` atomic write.
#[must_use]
pub fn render_env_file(spec: &TopologySpec, secrets: &GeneratedSecrets) -> String {
    let public_url = spec.public_domain.as_deref().map_or_else(
        || "http://127.0.0.1:8080".to_owned(),
        |d| format!("https://{d}"),
    );
    let acme_email = spec.acme_email.as_deref().unwrap_or("");
    let bind_addr = match spec.mode {
        ClusterMode::Monolithic => "127.0.0.1:8080".to_owned(),
        ClusterMode::Server => "127.0.0.1:8080".to_owned(),
        ClusterMode::Boxer => spec
            .vlan_ip
            .map_or_else(|| "127.0.0.1:8081".to_owned(), |ip| format!("{ip}:8081")),
    };

    let mut lines = vec![
        "# Generated by agents-installer — keep permissions strictly 0600".to_owned(),
        "AGENTS_ENV=production".to_owned(),
        format!("AGENTS_BIND_ADDR={bind_addr}"),
        format!("AGENTS_PUBLIC_URL={public_url}"),
        format!("AGENTS_TRUSTED_ORIGINS={public_url}"),
        format!("AGENTS_JWT_SECRET={}", secrets.jwt_secret),
        format!(
            "AGENTS_CREDENTIAL_MASTER_KEY={}",
            secrets.credential_master_key
        ),
        format!("AGENTS_POSTGRES_PASSWORD={}", secrets.postgres_password),
        format!(
            "DATABASE_URL=postgres://agents:{}@127.0.0.1:5432/agents?sslmode=disable",
            secrets.postgres_password
        ),
        format!("VALKEY_PASSWORD={}", secrets.valkey_password),
        format!(
            "VALKEY_URL=redis://:{}@127.0.0.1:6379",
            secrets.valkey_password
        ),
        format!("NATS_URL={}", spec.nats_url),
        format!("NATS_NKEY_SEED={}", secrets.nats_nkey_seed),
        format!("BOXER_RUNTIME={}", spec.runtime.label()),
        format!("BOXER_ISOLATION={}", spec.isolation.as_str()),
        format!("BOXER_MAX_CONCURRENT_BOXES={}", spec.max_boxes),
        format!("TRAEFIK_PREVIEW_DOMAIN={}", spec.preview_domain),
        format!("TRAEFIK_ACME_EMAIL={acme_email}"),
        format!("TRAEFIK_VLAN_SUBNET={}", spec.vlan_cidr),
    ];

    if let Some(ip) = spec.vlan_ip {
        lines.push(format!("BOXER_VLAN_IP={ip}"));
    }
    lines.push(String::new());
    lines.join("\n")
}

/// Renders a redacted preview of `.env` safe to display on terminal or dry-run logs.
#[must_use]
pub fn render_redacted_preview(spec: &TopologySpec, secrets: &GeneratedSecrets) -> String {
    let raw = render_env_file(spec, secrets);
    raw.lines()
        .map(|line| {
            if is_sensitive_env_line(line) {
                if let Some((key, _)) = line.split_once('=') {
                    format!("{key}=[REDACTED]")
                } else {
                    line.to_owned()
                }
            } else {
                line.to_owned()
            }
        })
        .collect::<Vec<_>>()
        .join("\n")
}

fn is_sensitive_env_line(line: &str) -> bool {
    const PREFIXES: &[&str] = &[
        "AGENTS_JWT_SECRET=",
        "AGENTS_CREDENTIAL_MASTER_KEY=",
        "AGENTS_POSTGRES_PASSWORD=",
        "DATABASE_URL=",
        "VALKEY_PASSWORD=",
        "VALKEY_URL=",
        "NATS_NKEY_SEED=",
    ];
    PREFIXES.iter().any(|p| line.starts_with(p))
}

/// Writes rendered `.env` safely with `0600` permissions on Unix systems.
///
/// # Errors
///
/// Returns [`InstallerError::Io`] on filesystem permission or write failure.
pub fn write_env_file_secure(path: &Path, content: &str) -> Result<(), InstallerError> {
    if let Some(parent) = path.parent()
        && !parent.as_os_str().is_empty()
    {
        fs::create_dir_all(parent)?;
    }
    fs::write(path, content.as_bytes())?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        fs::set_permissions(path, fs::Permissions::from_mode(0o600))?;
    }
    Ok(())
}
